def button(glyph: str, pushed: bool) -> Image.Image:
    img = Image.new("RGB", (24, 24), FACE_ON if pushed else FACE)
    px = img.load()
    top, bottom = (SHADOW, LIGHT) if pushed else (LIGHT, SHADOW)
    for i in range(24):
        px[i, 0] = px[0, i] = EDGE
        px[i, 23] = px[23, i] = EDGE
    for i in range(1, 23):
        px[i, 1] = px[1, i] = top
        px[i, 22] = px[22, i] = bottom
    rows = [r for r in glyph.strip("\n").split("\n")]
    shift = 1 if pushed else 0
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                px[4 + x + shift, 4 + y + shift] = INK
            elif ch == "o":
                px[4 + x + shift, 4 + y + shift] = GLOW if pushed else LIGHT
    return img


for name, glyph in GLYPHS.items():
    if name == "help":
        button(glyph, False).save(os.path.join(OUT, "btn_help.png"))
        continue
    sheet = Image.new("RGB", (24, 48))
    sheet.paste(button(glyph, False), (0, 0))
    sheet.paste(button(glyph, True), (0, 24))
    sheet.save(os.path.join(OUT, f"btn_{name}.png"))
